    await assert.rejects(command('fail', { notes: 'No' }), /failure reason/);
    result = await command('fail', { notes: 'Customer unavailable at address' }); assert.equal(result.status, 'failed');
    water = true;
    Object.assign(sub, { portalType: 'water', userId: ids.user, quantity: 2, unitPrice: 30, scheduleVersion: 2, billingCycle: 'weekly' });
    weeklyHoliday = 'Thursday';
