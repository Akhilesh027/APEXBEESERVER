      if (filter.outstanding?.$gte > account.outstanding || filter.depositPaise?.$gte > account.depositPaise) return null;
      account.outstanding += update.$inc.outstanding ?? 0;
      account.depositPaise += update.$inc.depositPaise ?? 0;
