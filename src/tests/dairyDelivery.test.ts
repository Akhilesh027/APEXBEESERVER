    mock(BusinessCalendar, 'findOne', () => query(holiday ? {} : null));
    mock(BusinessApplication, 'findOne', () => query({ businessDetails: { dairy: { weeklyHoliday } } }));
    mock(DeliveryPartner, 'findOne', (filter: any) => { assert.equal(filter.status, 'active'); assert.equal(filter.userId, ids.rider); return query(eligibleRider ? { userId: ids.rider } : null); });
    mock(SubscriptionDeliveryTask, 'findOneAndUpdate', async (filter: any, update: any, options: any) => {
      assert.ok(options.session);
      if (conflict) return null;
      if (!task) task = { _id: ids.task, ...update.$setOnInsert, save: async () => task };
      if (filter._id) assert.equal(filter.status, task.status);
      Object.assign(task, update.$set); return task;
    });
    mock(SubscriptionDeliveryTask, 'updateOne', async (_filter: any, update: any) => { task.otpAttempts = (task.otpAttempts || 0) + update.$inc.otpAttempts; });
    mock(LocalShopSubscription, 'updateOne', async (_filter: any, update: any, options: any) => { histories++; assert.ok(options.session); assert.ok(update.$push.deliveryHistory); });
    await assert.rejects(command('start'), /Assign a rider/);
