    weeklyHoliday = 'Thursday'; await assert.rejects(command('assign', { riderId: ids.rider }), /holiday/); weeklyHoliday = 'None';
    let result = await command('assign', { riderId: ids.rider }); assert.equal(result.status, 'assigned'); assert.equal('otp' in result, false); assert.match(task.otp, /^\d{6}$/);
    await assert.rejects(command('deliver', { otp: task.otp }), /Start the delivery/);
    result = await command('start'); assert.equal(result.status, 'started');
    await assert.rejects(command('assign', { riderId: ids.rider }), /cannot be reassigned/);
    await assert.rejects(command('deliver'), /OTP or upload/);
    await assert.rejects(command('deliver', { otp: '000000' }), /does not match/); assert.equal(task.otpAttempts, 1); assert.equal(histories, 0);
    await assert.rejects(command('deliver', { vendor: undefined, riderUserId: ids.user, otp: task.otp }), /not assigned/);
    conflict = true; await assert.rejects(command('deliver', { otp: task.otp }), /delivery changed/); conflict = false;
