    mock(mongoose, 'startSession', async () => ({ withTransaction: async (callback: any) => callback(), endSession: async () => {} }));
    mock(LocalShopSubscription, 'findOne', (filter: any) => { if (filter.vendorId) assert.equal(filter.vendorId, ids.vendor); return query(sub); });
    mock(Vendor, 'findById', () => query(vendor));
